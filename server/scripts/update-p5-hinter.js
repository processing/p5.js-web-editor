axios
  .get('https://p5js.org/reference/data.json')
  .then((response) => {
    const { data } = response;

    const arr = data.classitems;
    const p5Keywords = [];

    arr.forEach((obj) => {
      if (
        obj.class === 'p5' &&
        obj.module !== 'Foundation' &&
        obj.name &&
        obj.itemtype
      ) {
        let itemType;
        let params = [];
        if (obj.itemtype === 'method') {
          itemType = 'method';

          // Adds the parameters to the method.
          // I'm not sure this will be used but we can at least keep it around.
          params = obj.params?.map((param) => ({
            p: param.name, // param name
            o: param.optional ?? false // optional
          }));
        } else if (obj.itemtype === 'property') {
          itemType = obj.module === 'Constants' ? 'constant' : 'variable';
        } else itemType = 'attr';

        p5Keywords.push({
          label: obj.name,
          type: itemType,
          params,
          p5DocPath: obj.name
        });
      }
    });

    ['true', 'false'].forEach((bol) => {
      p5Keywords.push({
        label: bol,
        type: 'boolean',
        p5DocPath: 'boolean'
      });
    });

    reservedKeywords.forEach((keyword) => {
      p5Keywords.push({
        label: keyword.name,
        type: 'keyword',
        p5DocPath: keyword.p5DocPath
      });
    });

    reservedObjects.forEach((keyword) => {
      p5Keywords.push({
        label: keyword.name,
        type: 'obj',
        p5DocPath: keyword.p5DocPath
      });
    });

    const keywords = JSON.stringify(p5Keywords);

    let generatedCode = '/* eslint-disable */\n';
    generatedCode +=
      '/* generated: do not edit! helper file for hinter.' +
      ' generated by update-p5-hinter script */\n';
    generatedCode += `exports.p5Hinter = ${keywords};\n`;

    fs.writeFile(
      `${process.cwd()}/client/utils/p5-hinter.js`,
      generatedCode,
      (error) => {
        if (error) {
          console.log("Error!! Couldn't write to the file", error);
        } else {
          console.log('Hinter files updated successfully');
        }
      }
    );
  })
  .catch((err) => {
    throw err;
  });
